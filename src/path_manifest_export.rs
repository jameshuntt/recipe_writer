use std::collections::{BTreeMap, BTreeSet};

use crate::path_manifest::{Cardinality, PathManifest, PathSpec, ValueKind};

/// Stable, pathgen-facing export contract for recipe path manifests.
///
/// `PathManifest` is the in-process authoring structure. `PathgenManifestV1`
/// is the narrow handoff shape pathgen can consume without knowing how
/// `recipe_writer` parses streams, switches schemas, or records frame receipts.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PathgenManifestV1 {
    pub schema_version: u16,
    pub namespace: String,
    pub program_name: String,
    pub paths: Vec<PathgenPathSpecV1>,
}

impl PathgenManifestV1 {
    pub const SCHEMA_VERSION: u16 = 1;

    pub fn from_manifest(manifest: &PathManifest) -> Self {
        let mut seen_const_names: BTreeMap<String, usize> = BTreeMap::new();
        let mut paths = manifest.paths.clone();
        paths.sort_by(|left, right| left.path.cmp(&right.path));

        let paths = paths
            .into_iter()
            .map(|spec| export_spec(spec, &mut seen_const_names))
            .collect();

        Self {
            schema_version: Self::SCHEMA_VERSION,
            namespace: manifest.namespace.clone(),
            program_name: manifest.program_name.clone(),
            paths,
        }
    }

    pub fn contains_path(&self, path: &str) -> bool {
        self.paths.iter().any(|spec| spec.path == path)
    }

    pub fn get(&self, path: &str) -> Option<&PathgenPathSpecV1> {
        self.paths.iter().find(|spec| spec.path == path)
    }

    /// Deterministic line-oriented export for tools that do not want a Rust dependency.
    ///
    /// The format is intentionally boring and append-only:
    ///
    /// ```text
    /// PATHGEN_MANIFEST_V1
    /// namespace\t<namespace>
    /// program\t<program_name>
    /// path\t<const_name>\t<value_kind>\t<cardinality>\t<produced_by_schema>\t<path>
    /// ```
    pub fn to_manifest_lines(&self) -> String {
        let mut out = String::new();
        out.push_str("PATHGEN_MANIFEST_V1\n");
        out.push_str(&format!("namespace\t{}\n", self.namespace));
        out.push_str(&format!("program\t{}\n", self.program_name));
        for spec in &self.paths {
            out.push_str(&format!(
                "path\t{}\t{}\t{}\t{}\t{}\n",
                spec.const_name,
                spec.value_kind,
                spec.cardinality,
                spec.produced_by_schema,
                spec.path
            ));
        }
        out
    }

    /// Emit simple Rust string constants that pathgen can include or mirror.
    pub fn to_rust_constants(&self) -> String {
        let mut out = String::new();
        out.push_str("// @generated by recipe_writer path manifest export v1\n");
        out.push_str(&format!(
            "pub const PATHGEN_MANIFEST_VERSION: u16 = {};\n",
            self.schema_version
        ));
        for spec in &self.paths {
            out.push_str(&format!(
                "pub const {}: &str = \"{}\";\n",
                spec.const_name,
                escape_rust_str(&spec.path)
            ));
        }
        out
    }

    pub fn const_names_are_unique(&self) -> bool {
        let mut names = BTreeSet::new();
        self.paths
            .iter()
            .all(|spec| names.insert(spec.const_name.as_str()))
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PathgenPathSpecV1 {
    pub path: String,
    pub const_name: String,
    pub value_kind: String,
    pub cardinality: String,
    pub produced_by_schema: String,
}

fn export_spec(
    spec: PathSpec,
    seen_const_names: &mut BTreeMap<String, usize>,
) -> PathgenPathSpecV1 {
    let base_const_name = const_name_for_path(&spec.path);
    let count = seen_const_names.entry(base_const_name.clone()).or_insert(0);
    let const_name = if *count == 0 {
        base_const_name
    } else {
        format!("{}_{}", base_const_name, *count + 1)
    };
    *count += 1;

    PathgenPathSpecV1 {
        path: spec.path,
        const_name,
        value_kind: value_kind_name(spec.value_kind).to_string(),
        cardinality: cardinality_name(spec.cardinality).to_string(),
        produced_by_schema: spec.produced_by_schema,
    }
}

pub fn const_name_for_path(path: &str) -> String {
    let mut out = String::new();
    let mut last_was_underscore = false;

    for ch in path.chars() {
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_uppercase());
            last_was_underscore = false;
        } else if ch == '*' {
            // Wildcard markers are represented by the repeated segment itself.
            continue;
        } else if !last_was_underscore {
            out.push('_');
            last_was_underscore = true;
        }
    }

    let trimmed = out.trim_matches('_').to_string();
    if trimmed.is_empty() {
        "PATH".to_string()
    } else if trimmed.chars().next().is_some_and(|ch| ch.is_ascii_digit()) {
        format!("PATH_{}", trimmed)
    } else {
        trimmed
    }
}

fn value_kind_name(kind: ValueKind) -> &'static str {
    match kind {
        ValueKind::U8 => "u8",
        ValueKind::U16 => "u16",
        ValueKind::U32 => "u32",
        ValueKind::U64 => "u64",
        ValueKind::Binary => "binary",
        ValueKind::String => "string",
        ValueKind::Struct => "struct",
        ValueKind::Array => "array",
        ValueKind::Unknown => "unknown",
    }
}

fn cardinality_name(cardinality: Cardinality) -> &'static str {
    match cardinality {
        Cardinality::Single => "single",
        Cardinality::Repeated => "repeated",
    }
}

fn escape_rust_str(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::path_manifest::{Cardinality, PathManifest, PathSpec, ValueKind};

    #[test]
    fn const_name_for_path_is_stable_for_wildcard_paths() {
        assert_eq!(
            const_name_for_path("http3.stream_minimal.frames[*].frame_type"),
            "HTTP3_STREAM_MINIMAL_FRAMES_FRAME_TYPE"
        );
    }

    #[test]
    fn export_contract_is_deterministic_and_pathgen_ready() {
        let mut manifest = PathManifest::new("http3", "stream_minimal");
        manifest.add(PathSpec::new(
            "http3.stream_minimal.frames[*].payload.active_schema.qpack_block",
            ValueKind::Binary,
            Cardinality::Repeated,
            "http3_headers_frame",
        ));
        manifest.add(PathSpec::new(
            "http3.stream_minimal.frames[*].frame_type",
            ValueKind::U64,
            Cardinality::Repeated,
            "http3_frame_minimal",
        ));

        let export = PathgenManifestV1::from_manifest(&manifest);

        assert_eq!(export.schema_version, 1);
        assert!(export.const_names_are_unique());
        assert_eq!(
            export.paths[0].path,
            "http3.stream_minimal.frames[*].frame_type"
        );
        assert_eq!(
            export.paths[0].const_name,
            "HTTP3_STREAM_MINIMAL_FRAMES_FRAME_TYPE"
        );
        assert_eq!(export.paths[0].value_kind, "u64");
        assert_eq!(export.paths[0].cardinality, "repeated");

        let lines = export.to_manifest_lines();
        assert!(lines.starts_with("PATHGEN_MANIFEST_V1\n"));
        assert!(lines.contains(
            "path\tHTTP3_STREAM_MINIMAL_FRAMES_FRAME_TYPE\tu64\trepeated\thttp3_frame_minimal\thttp3.stream_minimal.frames[*].frame_type"
        ));

        let constants = export.to_rust_constants();
        assert!(constants.contains(
            "pub const HTTP3_STREAM_MINIMAL_FRAMES_FRAME_TYPE: &str = \"http3.stream_minimal.frames[*].frame_type\";"
        ));
    }
}
